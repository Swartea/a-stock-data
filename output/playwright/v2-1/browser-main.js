async (page) => {
 const check=(ok,message)=>{if(!ok)throw new Error(message);};
 await page.evaluate(()=>localStorage.removeItem('swartea.market-research.watchlist.v1'));
 await page.reload();
 const errors=[];page.on('pageerror',e=>errors.push(String(e)));
 await page.setViewportSize({width:1440,height:1000});
 await page.getByRole('button',{name:'市场总览',exact:true}).click();
 await page.waitForFunction(()=>[...document.querySelectorAll('#strip [data-field="close"]')].every(e=>!e.textContent.includes('读取')));
 check(await page.locator('#strip .mcard').count()===9,'nine Registry cards');
 await page.screenshot({path:'output/playwright/v2-1/overview-1440.png',fullPage:true});
 await page.getByRole('button',{name:'加入自选',exact:true}).first().press('Enter');
 check(await page.locator('#section-overview').isVisible(),'keyboard watch must not navigate');
 await page.getByRole('button',{name:'自选关注',exact:true}).click();
 check(await page.locator('#watch-list .watch-card').count()===1,'add watch');
 await page.reload();
 await page.getByRole('button',{name:'自选关注',exact:true}).click();
 check(await page.locator('#watch-list .watch-card').count()===1,'reload persistence');
 await page.locator('#watch-list [data-action="open"]').click();
 check(await page.locator('#section-research').isVisible(),'watch research navigation');
 await page.waitForFunction(()=>document.querySelector('#state').classList.contains('ok'));
 const chart=page.locator('#chart');await chart.hover();
 check((await page.locator('#probe').textContent()).includes('开'),'OHLC pointer');
 await page.locator('#zoom').selectOption('40');
 await page.getByRole('button',{name:'后一段 →'}).click();
 await page.screenshot({path:'output/playwright/v2-1/research-1440.png',fullPage:true});
 await page.getByRole('button',{name:'自选关注',exact:true}).click();
 await page.locator('#watch-list [data-action="watch"]').press('Enter');
 check(await page.locator('#section-watchlist').isVisible(),'keyboard remove must not navigate');
 check(await page.locator('#watch-empty').isVisible(),'remove and empty');
 await page.getByRole('button',{name:'市场比较',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('#compare-message').textContent.includes('共同基准日'));
 check(await page.locator('.compare-series').count()===3,'three cross market series');
 await page.locator('#compare-chart').hover();
 check((await page.locator('#compare-probe').textContent()).includes('累计'),'comparison tooltip');
 const counts={};
 for(const width of [1920,1440,1280,768,390]){
   await page.setViewportSize({width,height:width<=768?844:1080});
   await page.waitForTimeout(150);
   check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'compare overflow '+width);
   counts[width]=await page.locator('.compare-series').count();
   await page.screenshot({path:'output/playwright/v2-1/comparison-'+width+'.png',fullPage:true});
   await page.getByRole('button',{name:'市场总览',exact:true}).click();
   check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'overview overflow '+width);
   await page.screenshot({path:'output/playwright/v2-1/overview-'+width+'.png',fullPage:true});
   await page.getByRole('button',{name:'指数研究',exact:true}).click();
   check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'research overflow '+width);
   if(width===390)await page.screenshot({path:'output/playwright/v2-1/research-390.png',fullPage:true});
   await page.getByRole('button',{name:'市场比较',exact:true}).click();
 }
 await page.getByRole('button',{name:'移除Nasdaq Composite',exact:true}).click();
 await page.waitForFunction(()=>document.querySelectorAll('.compare-series').length===2);
 await page.locator('#compare-start').fill('2026-09-01');
 await page.locator('#compare-end').fill('2026-10-15');
 await page.getByRole('button',{name:'比较走势',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('#compare-message').textContent.includes('共同基准日'));
 check(await page.locator('.compare-series').count()===2,'range comparison');
 check(errors.length===0,'console errors: '+errors.join(','));
 return {status:'PASS',viewports:counts,errors};
}
